#!/usr/bin/env python3
"""
Build ready-to-publish HTML pages for the /insights articles.

Usage:
    python3 publishing/build_articles.py [--as-of YYYY-MM-DD] [--out DIR]

Only articles whose week in publishing/schedule.json has started by --as-of
(default: today) are built, and articles listed in publishing/hold.txt are
skipped. Links to articles that are not live yet become plain text, so every
weekly build has no broken links. Rebuild every week: earlier pages (the
pillar guide, the FAQ hub) pick up links to the newly published articles.

Output in DIR (default: publishing/dist):
    insights/<slug>.html          full page (served at /insights/<slug> on Cloudflare Pages)
    fragments/<slug>.head.html    <title>, meta, canonical and JSON-LD for your own template
    fragments/<slug>.body.html    the article body only
    sitemap-insights.xml          the published articles
    insights-list.html            a link list for your /insights index page

No third-party packages needed: runs on the python3 that ships with macOS.
"""
import argparse
import datetime
import html
import json
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ARTICLES = os.path.join(ROOT, "articles")
HERE = os.path.join(ROOT, "publishing")

SITE = "https://rsphotographysg.com"
MARKER = "<!-- generated by seo-data/publishing/build_articles.py -->"

# Pages that already exist on the live site. Change /contact if the contact page has another URL.
EXISTING_PATHS = {
    "/contact": "/contact",
    "/rates": "/rates",
    "/insights/event-videography-rates-singapore": "/insights/event-videography-rates-singapore",
    "/insights/pdpa-event-photography-consent-guide": "/insights/pdpa-event-photography-consent-guide",
}

# [EXTERNAL LINK: ...] placeholders. Placeholders not listed here are removed.
EXTERNAL_LINKS = {
    "IPOS or Singapore Statutes Online page on the Copyright Act 2021":
        ("https://sso.agc.gov.sg/Act/CA2021", "Copyright Act 2021, Singapore Statutes Online"),
    "WSH Council – bizSAFE programme":
        ("https://www.wshc.sg/", "Workplace Safety and Health Council"),
    "PDPC decision on Iapps Pte Ltd, 2021":
        ("https://www.pdpc.gov.sg/", "Personal Data Protection Commission"),
    "Meteorological Service Singapore forecast page":
        ("https://www.weather.gov.sg/", "Meteorological Service Singapore"),
}

CSS = """
:root{--ink:#1d1d1f;--muted:#5f6368;--line:#e3e3e3;--accent:#b8860b;--bg:#fff}
body{margin:0;background:var(--bg);color:var(--ink);font:17px/1.65 -apple-system,BlinkMacSystemFont,"Segoe UI",Roboto,Helvetica,Arial,sans-serif}
.rs-article{max-width:760px;margin:0 auto;padding:32px 16px 64px}
.rs-article h1{font-size:2rem;line-height:1.25;margin:0 0 16px}
.rs-article h2{font-size:1.45rem;margin:40px 0 12px}
.rs-article h3{font-size:1.15rem;margin:28px 0 8px}
.rs-article a{color:var(--accent)}
.rs-article hr{border:0;border-top:1px solid var(--line);margin:32px 0}
.rs-article table{width:100%;border-collapse:collapse;margin:16px 0;font-size:.95rem;display:block;overflow-x:auto}
.rs-article th,.rs-article td{border:1px solid var(--line);padding:8px 10px;text-align:left;vertical-align:top}
.rs-article th{background:#f7f7f7}
.rs-article ul.checklist{list-style:none;padding-left:0}
.rs-article ul.checklist li:before{content:"\\2610  ";color:var(--muted)}
.rs-article code{background:#f3f3f3;padding:1px 5px;border-radius:4px;font-size:.9em}
.rs-article .source{color:var(--muted);font-size:.9em}
"""


def load_articles():
    arts = {}
    for name in sorted(os.listdir(ARTICLES)):
        if not (name.startswith("20") and name.endswith(".md")):
            continue
        text = open(os.path.join(ARTICLES, name), encoding="utf-8").read()
        m = re.match(r"---\n(.*?)\n---\n", text, re.S)
        if not m:
            continue
        meta = {}
        for line in m.group(1).splitlines():
            k, _, v = line.partition(":")
            v = v.strip()
            if v.startswith('"') and v.endswith('"'):
                v = v[1:-1]
            meta[k.strip()] = v
        slug = meta["slug"].split("/", 1)[1]
        body = text[m.end():]
        blocks = re.findall(r"```json\n(.*?)```", body, re.S)
        cut = body.find("\n## SEO Metadata")
        if cut != -1:
            body = body[:cut]
        body = re.sub(r"(\s*---\s*)+$", "\n", body)
        arts[slug] = {"meta": meta, "body": body, "jsonld": [json.loads(b) for b in blocks], "file": name}
    return arts


def load_hold():
    path = os.path.join(HERE, "hold.txt")
    held = set()
    if os.path.exists(path):
        for line in open(path, encoding="utf-8"):
            line = line.split("#", 1)[0].strip()
            if line:
                held.add(line)
    return held


class Linker:
    def __init__(self, live):
        self.live = live

    def internal(self, m):
        path, text = m.group(1), m.group(2)
        if path in EXISTING_PATHS:
            return '<a href="%s">%s</a>' % (EXISTING_PATHS[path], text)
        if path.startswith("/insights/") and path[len("/insights/"):] in self.live:
            return '<a href="%s">%s</a>' % (path, text)
        return text  # not live yet: plain text

    def external(self, m):
        label = html.unescape(m.group(1))
        if label in EXTERNAL_LINKS:
            url, text = EXTERNAL_LINKS[label]
            return '<span class="source">(Source: <a href="%s" rel="noopener">%s</a>)</span>' % (url, html.escape(text))
        return ""


def inline(text, linker):
    t = html.escape(text, quote=False)
    t = re.sub(r'\[INTERNAL LINK: (\S+) "([^"]+)"\]', linker.internal, t)
    t = re.sub(r"\[EXTERNAL LINK: ([^\]]+)\]", linker.external, t)
    t = re.sub(r"`([^`]+)`", r"<code>\1</code>", t)
    t = re.sub(r"\*\*(.+?)\*\*", r"<strong>\1</strong>", t)
    t = re.sub(r"(?<![\w*])\*(?!\s)(.+?)(?<!\s)\*(?![\w*])", r"<em>\1</em>", t)
    t = re.sub(r"\[([^\]]+)\]\((https?://[^)\s]+)\)", r'<a href="\2">\1</a>', t)
    return re.sub(r"\s+", " ", t).strip()


def heading_id(text):
    return re.sub(r"[^a-z0-9]+", "-", re.sub(r"<[^>]+>", "", text).lower()).strip("-")


def md_to_html(md, linker):
    lines = md.split("\n")
    out, para, i = [], [], 0

    def flush():
        if para:
            parts = []
            for p in para:
                s = inline(p, linker)
                if p.lstrip().startswith("→"):
                    # an arrow line whose links are all not live yet is dropped
                    if "<a " not in s:
                        continue
                    parts.append("<br>" + s if parts else s)
                else:
                    parts.append(s)
            if parts:
                out.append("<p>%s</p>" % " ".join(parts))
            para.clear()

    while i < len(lines):
        line = lines[i]
        s = line.strip()
        if not s:
            flush(); i += 1; continue
        if re.fullmatch(r"-{3,}", s):
            flush(); out.append("<hr>"); i += 1; continue
        h = re.match(r"(#{1,4}) (.*)", s)
        if h:
            flush()
            lvl, txt = len(h.group(1)), inline(h.group(2), linker)
            out.append('<h%d id="%s">%s</h%d>' % (lvl, heading_id(txt), txt, lvl))
            i += 1; continue
        if s.startswith("|"):
            flush()
            rows = []
            while i < len(lines) and lines[i].strip().startswith("|"):
                rows.append(lines[i].strip()); i += 1
            cells = [[c.strip() for c in r.strip("|").split("|")] for r in rows]
            body = [r for r in cells[1:] if not all(re.fullmatch(r":?-{3,}:?", c) for c in r)]
            t = ["<table><thead><tr>%s</tr></thead><tbody>" % "".join("<th>%s</th>" % inline(c, linker) for c in cells[0])]
            for r in body:
                t.append("<tr>%s</tr>" % "".join("<td>%s</td>" % inline(c, linker) for c in r))
            t.append("</tbody></table>")
            out.append("".join(t)); continue
        if re.match(r"\s*([-*]|\d+\.) ", line):
            flush()
            items = []  # (indent, ordered, checkbox, text)
            while i < len(lines) and re.match(r"\s*([-*]|\d+\.) ", lines[i]):
                m = re.match(r"(\s*)([-*]|\d+\.) (\[[ xX]\] )?(.*)", lines[i])
                text = m.group(4)
                i += 1
                while i < len(lines) and lines[i].startswith("   ") and not re.match(r"\s*([-*]|\d+\.) ", lines[i]) and lines[i].strip():
                    text += " " + lines[i].strip(); i += 1
                items.append((len(m.group(1)), m.group(2)[0].isdigit(), bool(m.group(3)), text))
            out.append(render_list(items, linker)); continue
        para.append(s); i += 1
    flush()
    return "\n".join(out)


def render_list(items, linker):
    html_out, stack = [], []
    for indent, ordered, check, text in items:
        while stack and stack[-1][0] > indent:
            html_out.append("</li></%s>" % stack.pop()[1])
        if not stack or indent > stack[-1][0]:
            tag = "ol" if ordered else "ul"
            cls = ' class="checklist"' if check else ""
            html_out.append("<%s%s>" % (tag, cls))
            stack.append((indent, tag))
        else:
            html_out.append("</li>")
        html_out.append("<li>%s" % inline(text, linker))
    while stack:
        html_out.append("</li></%s>" % stack.pop()[1])
    return "".join(html_out)


def head_html(art, slug, date):
    meta = art["meta"]
    url = "%s/insights/%s" % (SITE, slug)
    stamp = "%sT09:00:00+08:00" % date
    blocks = []
    for b in art["jsonld"]:
        b = json.loads(json.dumps(b))
        if b.get("@type") == "Article":
            b["datePublished"] = stamp
            b["dateModified"] = stamp
        blocks.append('<script type="application/ld+json">\n%s\n</script>' % json.dumps(b, ensure_ascii=False, indent=2))
    e = lambda s: html.escape(s, quote=True)
    return "\n".join([
        "<title>%s</title>" % e(meta["title"]),
        '<meta name="description" content="%s">' % e(meta["description"]),
        '<link rel="canonical" href="%s">' % url,
        '<meta property="og:type" content="article">',
        '<meta property="og:title" content="%s">' % e(meta["title"]),
        '<meta property="og:description" content="%s">' % e(meta["description"]),
        '<meta property="og:url" content="%s">' % url,
        '<meta property="article:published_time" content="%s">' % stamp,
    ] + blocks)


def page_html(head, body):
    return """<!doctype html>
%s
<html lang="en-SG">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
%s
<style>%s</style>
</head>
<body>
<main class="rs-article">
<article>
%s
</article>
</main>
</body>
</html>
""" % (MARKER, head, CSS, body)


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--as-of", default=datetime.date.today().isoformat(), help="build articles scheduled on or before this date (YYYY-MM-DD)")
    ap.add_argument("--out", default=os.path.join(HERE, "dist"))
    args = ap.parse_args()
    as_of = datetime.date.fromisoformat(args.as_of)

    arts = load_articles()
    schedule = json.load(open(os.path.join(HERE, "schedule.json"), encoding="utf-8"))
    held = load_hold()

    missing = sorted(set(arts) - set(schedule))
    if missing:
        sys.exit("No date in publishing/schedule.json for: " + ", ".join(missing))

    live = {s for s, d in schedule.items() if s in arts and s not in held and datetime.date.fromisoformat(d) <= as_of}
    linker = Linker(live)

    for sub in ("insights", "fragments"):
        os.makedirs(os.path.join(args.out, sub), exist_ok=True)
    order = sorted(live, key=lambda s: (schedule[s], s))
    for slug in order:
        art = arts[slug]
        head = head_html(art, slug, schedule[slug])
        body = md_to_html(art["body"], linker)
        open(os.path.join(args.out, "insights", slug + ".html"), "w", encoding="utf-8").write(page_html(head, body))
        open(os.path.join(args.out, "fragments", slug + ".head.html"), "w", encoding="utf-8").write(head + "\n")
        open(os.path.join(args.out, "fragments", slug + ".body.html"), "w", encoding="utf-8").write(body + "\n")

    sm = ['<?xml version="1.0" encoding="UTF-8"?>', '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">']
    sm += ["  <url><loc>%s/insights/%s</loc><lastmod>%s</lastmod></url>" % (SITE, s, schedule[s]) for s in order]
    sm.append("</urlset>")
    open(os.path.join(args.out, "sitemap-insights.xml"), "w", encoding="utf-8").write("\n".join(sm) + "\n")

    li = ['<li><a href="/insights/%s">%s</a></li>' % (s, html.escape(arts[s]["meta"]["title"])) for s in reversed(order)]
    open(os.path.join(args.out, "insights-list.html"), "w", encoding="utf-8").write("<ul>\n%s\n</ul>\n" % "\n".join(li))

    upcoming = sorted((d, s) for s, d in schedule.items() if s not in live and s not in held)
    print("Built %d article(s) as of %s into %s" % (len(order), as_of, args.out))
    new = [s for s in order if schedule[s] > (as_of - datetime.timedelta(days=7)).isoformat()]
    if new:
        print("New this week: " + ", ".join(new))
    if held:
        print("On hold (publishing/hold.txt): " + ", ".join(sorted(held)))
    if upcoming:
        print("Next: %s on %s" % (upcoming[0][1], upcoming[0][0]))


if __name__ == "__main__":
    main()
