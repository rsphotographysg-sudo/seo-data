#!/usr/bin/env bash
# Weekly publish: build this week's articles, check them, copy them into the website and deploy.
#
#   ./publishing/publish.sh              publish everything scheduled up to today
#   ./publishing/publish.sh 2026-10-20   publish everything scheduled up to that date
#
# Set these two once (here, or as environment variables):
SITE_PUBLIC_DIR="${SITE_PUBLIC_DIR:-}"   # the website folder Cloudflare Pages serves, e.g. "$HOME/Sites/rsphotography/public"
DEPLOY_CMD="${DEPLOY_CMD:-}"             # e.g. "npx wrangler pages deploy . --project-name=rsphotography"; leave empty to deploy yourself
set -euo pipefail

REPO="$(cd "$(dirname "$0")/.." && pwd)"
AS_OF="${1:-$(date +%F)}"
OUT="$REPO/publishing/dist"

if [ -z "$SITE_PUBLIC_DIR" ] || [ ! -d "$SITE_PUBLIC_DIR" ]; then
  echo "Set SITE_PUBLIC_DIR at the top of publishing/publish.sh to your website folder first." >&2
  exit 1
fi

cd "$REPO"
git pull --ff-only origin main || echo "(could not update from GitHub; using the local copy)"

rm -rf "$OUT"
python3 publishing/build_articles.py --as-of "$AS_OF" --out "$OUT"
python3 structured-data-fix/fix_structured_data.py "$OUT"

mkdir -p "$SITE_PUBLIC_DIR/insights"
for f in "$OUT"/insights/*.html; do
  dest="$SITE_PUBLIC_DIR/insights/$(basename "$f")"
  if [ -f "$dest" ] && ! grep -q "generated by seo-data/publishing/build_articles.py" "$dest"; then
    echo "Skipped $dest: a page you made yourself already exists there." >&2
    continue
  fi
  cp "$f" "$dest"
done
cp "$OUT/sitemap-insights.xml" "$SITE_PUBLIC_DIR/sitemap-insights.xml"

# Check the whole website folder, not only the new pages.
python3 structured-data-fix/fix_structured_data.py "$SITE_PUBLIC_DIR"

if [ -n "$DEPLOY_CMD" ]; then
  (cd "$SITE_PUBLIC_DIR" && eval "$DEPLOY_CMD")
  echo "Deployed. Request indexing for the new page(s) in Search Console > URL Inspection."
else
  echo "Pages copied into $SITE_PUBLIC_DIR. Deploy the site as usual."
fi
